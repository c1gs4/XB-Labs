// Run: node server/session-toolbar.check.mjs — status in Chat/Logs, toolbar order, refresh; no hub/model.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const app = readFileSync(new URL('../app/js/app.js', import.meta.url), 'utf8');
const pill = {};
const runs = new Map([['s', { id: 's', mode: 'json', status: 'running' }]]);
const ctx = vm.createContext({ window: { __liveRuns: runs }, DB: { sessions: [{ id: 's', col: 'running' }] }, state: { activeTab: 's', page: 'session' }, CHAT: { s: { loaded: true, busy: false } }, document: { querySelector: () => pill, getElementById: () => null }, bubbleChat: () => true, toast() {} });
vm.runInContext(app.slice(app.indexOf('const SESS_ST ='), app.indexOf('/* Ports the open session')), ctx);
vm.runInContext(app.slice(app.indexOf('function chatPaint('), app.indexOf('setInterval(async () =>', app.indexOf('function chatPaint('))), ctx);
vm.runInContext("chatPaint('s')", ctx);
assert.equal(pill.className, 'sh-st idle', 'Logs must update status even without chat-bubbles');
assert.match(pill.innerHTML, /Idle/);
ctx.CHAT.s.busy = true;
vm.runInContext("chatPaint('s')", ctx);
assert.equal(pill.className, 'sh-st running');
runs.get('s').status = 'failed';
vm.runInContext("chatPaint('s')", ctx);
assert.equal(pill.className, 'sh-st failed');
const head = app.slice(app.indexOf('function sessHead('), app.indexOf('function worked('));
assert.ok(!head.includes('data-act="run-menu"'));
assert.ok(head.indexOf('data-act="session-refresh"') < head.indexOf('data-act="chat-search"'));
assert.match(head, /b\('term', 'terminal', 'Terminal'\)/);
let pulls = 0;
ctx.fetch = async () => ({ ok: true, json: async () => [{ id: 's', mode: 'json', status: 'idle' }] });
ctx.chatPull = async () => { pulls++; ctx.CHAT.s.busy = false; };
ctx.button = {};
await vm.runInContext("refreshSession('s', button)", ctx);
assert.equal(pulls, 1);
assert.equal(runs.get('s').status, 'idle');
assert.equal(ctx.button.disabled, false);
assert.equal(pill.className, 'sh-st idle');
assert.match(app, /prefs.chatLayout === 'term' \? 'term' : 'chat'/);
const jobs = readFileSync(new URL('../app/js/jobs.js', import.meta.url), 'utf8');
assert.match(jobs, /disableStdin: readOnly/);
assert.match(jobs, /if \(!readOnly && !replaying && attached\) send\(\{ type: 'input'/);
let cleanups = 0, mounts = 0;
ctx.window.__ptyCleanup = () => cleanups++;
ctx.document.getElementById = name => name === 'chat-term' ? { closest: () => null } : null;
ctx.mountTerminal = async (id) => { assert.equal(id, 's'); mounts++; };
await vm.runInContext("refreshSession('s', button)", ctx);
assert.equal(cleanups, 1); assert.equal(mounts, 1);
let notice;
ctx.toast = message => { notice = message; };
ctx.mountTerminal = async () => { throw new Error('fixture disconnect'); };
await vm.runInContext("refreshSession('s', button)", ctx);
assert.match(notice, /Refresh failed: fixture disconnect/);
assert.ok(!app.includes('readOnly: bubbleChat'));
console.log('session-toolbar.check ok — native Terminal, Refresh remounts/awaits attach, errors visible, status/order preserved');
