// Run: node server/session-ui.check.mjs — project folders survive clear/delete; terminal has one input.
import assert from 'node:assert/strict';
import { readFileSync, mkdtempSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import vm from 'node:vm';
const base = mkdtempSync(join(tmpdir(), 'xb-session-ui-'));
process.env.XBLABS_DB = join(base, 'test.db');
const db = await import('./db.mjs');
const folder = join(base, 'project'); mkdirSync(folder); writeFileSync(join(folder, 'keep.txt'), 'keep');
const a = db.createSession({ title: 'A', ws: 'Keep', cwd: folder, device: 'remote-box', agent: 'omp', kind: 'chat' });
const b = db.createSession({ title: 'B', ws: 'Keep', cwd: folder, device: 'remote-box', agent: 'omp', kind: 'chat' });
db.deleteSession(a.id);
assert.equal(db.listProjects().length, 1);
assert.deepEqual(db.deleteSessionsBy({ ws: 'Keep' }), [b.id]);
assert.equal(db.listSessions({}).length, 0);
assert.equal(db.listProjects()[0].cwd, folder);
assert.equal(db.listProjects()[0].device, 'remote-box');
assert.ok(existsSync(join(folder, 'keep.txt')));
const c = db.createSession({ title: 'C', ws: 'Last', cwd: folder, kind: 'chat' }); db.deleteSession(c.id);
assert.ok(db.listProjects().some((p) => p.ws === 'Last'));
db.hideProject('Keep'); assert.ok(db.hiddenProjects().some((p) => p.ws === 'Keep'));
db.unhideProject('Keep');
const persisted = execFileSync(process.execPath, ['--input-type=module', '-e', `import * as db from ${JSON.stringify(new URL('./db.mjs', import.meta.url).href)}; console.log(JSON.stringify(db.listProjects()));`], { encoding: 'utf8', env: process.env });
assert.equal(JSON.parse(persisted).length, 2);
const app = readFileSync(new URL('../app/js/app.js', import.meta.url), 'utf8');
const helper = app.match(/const showSessionComposer =[^\n]+/)[0];
const ctx = vm.createContext({ state: { chatView: 'chat' }, agentChat: (id) => id === 'terminal', bubbleChat: (id) => id === 'bubble' });
vm.runInContext(helper, ctx);
assert.equal(vm.runInContext("showSessionComposer('terminal')", ctx), false);
assert.equal(vm.runInContext("showSessionComposer('bubble')", ctx), true);
ctx.state.chatView = 'term';
assert.equal(vm.runInContext("showSessionComposer('bubble')", ctx), false);
assert.equal(vm.runInContext("showSessionComposer('shell')", ctx), true);
assert.match(app, /class="composer" \$\{showSessionComposer\(S.id\)/);
const live = readFileSync(new URL('../app/js/live.js', import.meta.url), 'utf8');
const start = live.indexOf('    LIVE.projects ='); const end = live.indexOf('    LIVE.logs =', start);
const render = vm.createContext({ projects: { folders: db.listProjects() }, LIVE: { hidden: new Set(), devices: [{ name: 'remote-box' }, { name: 'local' }] }, prefs: { goaMode: false }, DB: {}, shown: [] });
vm.runInContext(live.slice(start, end), render);
assert.ok(render.DB.workspaces.some((w) => w.id === 'Keep' && w.hosts === 'remote-box'));
assert.ok(render.DB.workspaces.some((w) => w.id === 'Last'));
render.LIVE.hidden.add('Keep'); vm.runInContext(`{${live.slice(start, end)}}`, render);
assert.ok(!render.DB.workspaces.some((w) => w.id === 'Keep'));
console.log('session-ui.check ok — clear/delete preserve folder and device, restart persistence, explicit hide, terminal composer hidden');
